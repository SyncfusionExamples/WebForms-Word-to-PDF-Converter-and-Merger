using System;
using System.Collections.Generic;
using System.Linq;
using System.Web;
using System.Web.Optimization;
using System.Web.Routing;
using System.Web.Security;
using System.Web.SessionState;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace Word_To_PDF_Converter_and_Merger
{
    public class Global : HttpApplication
    {
        void Application_Start(object sender, EventArgs e)
        {
            // Code that runs on application startup
            RouteConfig.RegisterRoutes(RouteTable.Routes);
            BundleConfig.RegisterBundles(BundleTable.Bundles);
        }

        const string BasePath = "/word-to-pdf-converter-and-merger";

        void Application_BeginRequest(object sender, EventArgs e)
        {
            // The app is published under a base path (e.g. https://syncfusiondemo.com/word-to-pdf-converter-and-merger).
            // Root-relative URLs generated by ASP.NET (bundles, scripts, content, form action) must carry that prefix.
            Response.Filter = new BasePathFilter(Response.Filter);
        }

        class BasePathFilter : Stream
        {
            static readonly Regex RootUrl = new Regex(
                "(\\s(?:src|href|action)\\s*=\\s*[\"'])/(?!/)(?!word-to-pdf-converter-and-merger(?:/|[\"'?#]))",
                RegexOptions.IgnoreCase | RegexOptions.Compiled);

            readonly Stream inner;
            readonly MemoryStream buffer = new MemoryStream();

            public BasePathFilter(Stream inner) { this.inner = inner; }

            public override void Write(byte[] data, int offset, int count) { buffer.Write(data, offset, count); }

            public override void Flush()
            {
                byte[] bytes = buffer.ToArray();
                buffer.SetLength(0);
                var response = HttpContext.Current == null ? null : HttpContext.Current.Response;
                if (response != null && response.ContentType != null &&
                    response.ContentType.StartsWith("text/html", StringComparison.OrdinalIgnoreCase))
                {
                    Encoding enc = response.ContentEncoding ?? Encoding.UTF8;
                    string html = RootUrl.Replace(enc.GetString(bytes), "$1" + BasePath + "/");
                    bytes = enc.GetBytes(html);
                }
                inner.Write(bytes, 0, bytes.Length);
                inner.Flush();
            }

            public override void Close() { Flush(); inner.Close(); base.Close(); }

            public override bool CanRead { get { return false; } }
            public override bool CanSeek { get { return false; } }
            public override bool CanWrite { get { return true; } }
            public override long Length { get { throw new NotSupportedException(); } }
            public override long Position { get { throw new NotSupportedException(); } set { throw new NotSupportedException(); } }
            public override int Read(byte[] b, int o, int c) { throw new NotSupportedException(); }
            public override long Seek(long o, SeekOrigin so) { throw new NotSupportedException(); }
            public override void SetLength(long v) { throw new NotSupportedException(); }
        }
    }
}
